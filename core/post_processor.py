COMPILED_PATTERNS = [(re.compile(p), r) for p, r in CORRECTION_PATTERNS]


def proofread_text(text: str) -> str:
    """Applies classical Dhamma & Grammar post-processing to raw OCR text."""
    if not text:
        return ""

    lines = []
    for line in text.splitlines():
        l = line.strip()
        if not l or "dhammadownload" in l.lower() or "http://" in l.lower():
            continue
        
        l = normalize_myanmar_unicode(l)
        # Apply compiled regex replacements
        for pat, repl in COMPILED_PATTERNS:
            l = pat.sub(repl, l)

        # Cleanup trailing spaces before punctuation
        l = re.sub(r"\s+([။၊])", r"\1", l)
        l = re.sub(r"([။၊])(?=[က-အ])", r"\1 ", l)
        lines.append(l)

    return "\n".join(lines)


